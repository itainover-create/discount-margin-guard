// Generates web/js/core/layout.js from core/include/osk/api.h so the JS host
// and the C++ core share one definition of the input/output block layout.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , header, outFile] = process.argv;
const src = readFileSync(header, 'utf8').replace(/\/\/.*$/gm, '');
let out = '// AUTO-GENERATED by tools/gen_layout.mjs from core/include/osk/api.h — do not edit.\n';
const enumRe = /enum\s+(\w+)\s*\{([^}]*)\}/g;
let m;
while ((m = enumRe.exec(src))) {
  const name = m[1];
  let value = -1;
  const entries = [];
  for (const raw of m[2].split(',')) {
    const item = raw.trim();
    if (!item) continue;
    const [k, v] = item.split('=').map((x) => x.trim());
    value = v !== undefined ? Number(v) : value + 1;
    entries.push(`  ${k}: ${value},`);
  }
  out += `export const ${name} = Object.freeze({\n${entries.join('\n')}\n});\n`;
}
writeFileSync(outFile, out);
console.log(`wrote ${outFile}`);
